<?php

namespace App\Mail;

use App\Models\User;
use Illuminate\Bus\Queueable;
use Illuminate\Mail\Mailable;
use Illuminate\Queue\SerializesModels;

class PublisherRegistrationConfirmation extends Mailable
{
    use Queueable, SerializesModels;

    public $user;

    public function __construct(User $user)
    {
        $this->user = $user;
    }

    public function build()
    {
        return $this->markdown('emails.publisher-registration-confirmation')
            ->subject("Welcome to Neesh - Your Application Received")
            ->with([
                'user' => $this->user,
            ]);
    }
}

